function toSessionRole(role: Role): SessionUser['role'] {
  switch (role) {
    case Role.Admin: return 'Admin'
    case Role.HSSE: return 'HSSE'
    case Role.AreaHead: return 'AreaHead'
    default: return 'Peminjam'
  }
}



